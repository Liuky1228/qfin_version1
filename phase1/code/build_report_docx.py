def _dual_keys(d):
    """让所有分阶段字典同时支持英文键和中文键"""
    if not isinstance(d, dict):
        return d
    if any(k in _EN2CN for k in d.keys()):
        for en, cn in _EN2CN.items():
            if en in d and cn not in d:
                d[cn] = d[en]
    else:
        for en, cn in _EN2CN.items():
            if cn in d:
                d[en] = d[cn]
    for k, v in list(d.items()):
        d[k] = _dual_keys(v)
    return d


