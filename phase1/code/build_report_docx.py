P("生命周期分类，就是给每家公司每一年打一个「阶段标签」。"
  "它的价值在于：同一个因子在不同阶段的含义可能相反。"
  "例如估值因子（低市盈率）在成熟期可能是「便宜」，在整合期可能是「价值陷阱」。"
  "Phase 2 要做的就是在控制阶段标签后重估因子有效性。")

H("2.2 为什么用「现金流符号」而不是「增长率」分类", 2)
P("学术上有两条主流路径：")
BUL("增长率法（如 Anthony & Ramesh 1992）：用营收增长率、股利支付率、资本支出增长率划分。"
    "问题是增长率波动大、易被操纵，且需要设定阈值，判断边界模糊。")
BUL("现金流符号法（Dickinson 2011）：只看经营、投资、筹资三类现金流的正负号。"
    "优点是阈值唯一（正负号没有自由度）、不受规模影响（除以总资产）、经济含义直接。")
P("我们采用第二条路径，原因是它可复现、参数少、不易被质疑「阈值怎么定的」。")

