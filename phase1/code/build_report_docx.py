H("4.3 第 2 层：为什么改造 CFI", 2)
P("原始 CFI（投资活动现金流）存在一个 A 股特有的问题："
  "A 股公司普遍用闲置资金购买理财产品，这些「买入理财」记在投资活动里，"
  "使 CFI 因非投资性支出而变负；赎回理财和投资收益则使 CFI 变正。"
  "结果是公司的投资活动现金流被金融性往来污染，无法反映真实投资行为。")
P("我们的改造公式：")
P("CFI_core = CFI + 投资所支付的现金 − 收回投资所收到的现金 − 取得投资收益收到的现金",
  bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
P("直观理解：把「买理财」加回（因为它不是真实投资），把「赎回理财」和「投资收益」减掉。"
  "这样得到的数字更接近「公司在真实建设产能上的投入」。")
P("我们同时测试了另一个口径 Capex（资本支出，即购建固定资产的现金），"
  "它在样本中可用率 "
  f"{av['capex']*100:.1f}%，可分类覆盖率 {R['可分类行数']['capex']['覆盖率']*100:.0f}%，"
  "介于两者之间。三种口径的结果在第 6 节对比。")

