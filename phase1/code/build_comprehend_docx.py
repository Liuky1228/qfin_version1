def H(text, lvl=1): doc.add_heading(text, level=lvl)

def P(text, bold=False, italic=False, size=None, color=None, align=None):
    p = doc.add_paragraph(); r = p.add_run(text)
    r.bold, r.italic = bold, italic
    if size: r.font.size = Pt(size)
    if color: r.font.color.rgb = color
    r.font.name = "Times New Roman"; _set_ea_run(r, "宋体")
    if align: p.alignment = align
    return p

def BUL(text, lvl=0):
    p = doc.add_paragraph(text, style="List Bullet" if lvl == 0 else "List Bullet 2")
    for r in p.runs:
        r.font.name = "Times New Roman"; _set_ea_run(r, "宋体")
    return p

def TBL(headers, rows, widths=None, note=None, size=9.0):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]; c.text = ""
        pp = c.paragraphs[0]; pp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = pp.add_run(str(h)); r.bold = True; r.font.size = Pt(size); _set_ea_run(r, "黑体")
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""; pp = cells[i].paragraphs[0]
            pp.alignment = WD_ALIGN_PARAGRAPH.CENTER if i > 0 else WD_ALIGN_PARAGRAPH.LEFT
            r = pp.add_run(str(v)); r.font.size = Pt(size); _set_ea_run(r, "宋体")
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    if note: P(note, italic=True, size=8.5)
    return t

def BOX(title):
    """小节内子块标题（【知识点扫盲】等）"""
    p = doc.add_paragraph()
    r = p.add_run(title); r.bold = True; r.font.size = Pt(11)
    r.font.color.rgb = RGBColor(0xC0, 0x50, 0x00); _set_ea_run(r, "黑体")
    p.paragraph_format.space_before = Pt(6)

def SAY(text):
    """口播稿：浅色底纹感的独立段落"""
    p = doc.add_paragraph()
    r = p.add_run("【汇报时这样说】"); r.bold = True; r.font.size = Pt(10.5)
    r.font.color.rgb = RGBColor(0x1F, 0x5C, 0x2E); _set_ea_run(r, "黑体")
    p2 = doc.add_paragraph()
    r2 = p2.add_run(text); r2.italic = True; r2.font.size = Pt(10.5)
    _set_ea_run(r2, "楷体")
    p2.paragraph_format.left_indent = Cm(0.5)
    return p2

def QA(q, a):
    p = doc.add_paragraph()
